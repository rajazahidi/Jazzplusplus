static const float kPi = 3.14159265358979323846f;

uint16_t JZBroadcastAudioWatermarkSteganographyEngine::calculateCrc16(const uint8_t* data, size_t len) {
    uint16_t crc = 0xFFFF;
    for (size_t i = 0; i < len; ++i) {
        crc ^= (uint16_t)data[i] << 8;
        for (int b = 0; b < 8; ++b) {
            if (crc & 0x8000) {
                crc = (crc << 1) ^ 0x1021; // CCITT polynomial
            } else {
                crc <<= 1;
            }
        }
    }
    return crc;
}

JZBroadcastAudioWatermarkSteganographyEngine::JZBroadcastAudioWatermarkSteganographyEngine(float sampleRate)
    : mSampleRate(sampleRate > 1000.0f ? sampleRate : 48000.0f)
    , mStrengthDb(-24.0f)
    , mCarrierHz(3200.0f)
    , mLastValid(false)
    , mLastDecodedPayload(0)
    , mLastConfidence(0.0f)
    , mBitErrorRate(0.0f)
    , mEmbedSampleCounter(0)
    , mEmbedCarrierPhase(0.0f)
    , mDetectSampleCounter(0)
    , mDetectCarrierPhase(0.0f)
{
    initPnSequence();
}

void JZBroadcastAudioWatermarkSteganographyEngine::setSampleRate(float sampleRate) {
    if (sampleRate > 1000.0f) {
        mSampleRate = sampleRate;
        reset();
    }
}

void JZBroadcastAudioWatermarkSteganographyEngine::setWatermarkStrengthDb(float db) {
    mStrengthDb = std::max(-48.0f, std::min(-12.0f, db));
}

void JZBroadcastAudioWatermarkSteganographyEngine::setCarrierFrequencyHz(float freqHz) {
    mCarrierHz = std::max(1000.0f, std::min(mSampleRate * 0.4f, freqHz));
}

void JZBroadcastAudioWatermarkSteganographyEngine::initPnSequence() {
    // 63-bit maximal-length sequence (m-sequence) generated by 6th-order LFSR
    // Polynomial: x^6 + x^5 + 1
    mPnSequence.resize(CHIPS_PER_BIT);
    uint8_t lfsr = 0x3F; // seed: 6 ones
    for (size_t i = 0; i < CHIPS_PER_BIT; ++i) {
        uint8_t bit = ((lfsr >> 5) ^ (lfsr >> 4)) & 1;
        lfsr = ((lfsr << 1) | bit) & 0x3F;
        mPnSequence[i] = (bit == 1) ? 1.0f : -1.0f;
    }
}

void JZBroadcastAudioWatermarkSteganographyEngine::reset() {
    mLastValid = false;
    mLastDecodedPayload = 0;
    mLastConfidence = 0.0f;
    mBitErrorRate = 0.0f;
    mEmbedSampleCounter = 0;
    mEmbedCarrierPhase = 0.0f;
    mDetectSampleCounter = 0;
    mDetectCarrierPhase = 0.0f;
    mBitCorrelators.clear();
    mReceivedBits.clear();
}

std::vector<uint8_t> JZBroadcastAudioWatermarkSteganographyEngine::serializeFrame(uint32_t payload, uint16_t crc) {
    std::vector<uint8_t> bits;
    bits.reserve(TOTAL_FRAME_BITS);

    // 1. Sync preamble (16 bits)
    for (int i = 15; i >= 0; --i) {
        bits.push_back((SYNC_PREAMBLE >> i) & 1);
    }
    // 2. Payload (32 bits)
    for (int i = 31; i >= 0; --i) {
        bits.push_back((payload >> i) & 1);
    }
    // 3. CRC (16 bits)
    for (int i = 15; i >= 0; --i) {
        bits.push_back((crc >> i) & 1);
    }

    return bits;
}

void JZBroadcastAudioWatermarkSteganographyEngine::embedWatermark(const float* inL, const float* inR,
                                                                 float* outL, float* outR,
                                                                 size_t numSamples,
                                                                 uint32_t payload32) {
    if (!inL || !inR || !outL || !outR || numSamples == 0) return;

    // Calculate CRC of payload (4 bytes)
    uint8_t payloadBytes[4];
    payloadBytes[0] = (payload32 >> 24) & 0xFF;
    payloadBytes[1] = (payload32 >> 16) & 0xFF;
    payloadBytes[2] = (payload32 >> 8)  & 0xFF;
    payloadBytes[3] = (payload32)       & 0xFF;
    uint16_t crc = calculateCrc16(payloadBytes, 4);

    std::vector<uint8_t> frameBits = serializeFrame(payload32, crc);

    float linearStrength = std::pow(10.0f, mStrengthDb / 20.0f);
    float carrierPhaseInc = 2.0f * kPi * mCarrierHz / mSampleRate;
    size_t samplesPerBit = CHIPS_PER_BIT * SAMPLES_PER_CHIP;
    size_t totalFrameSamples = TOTAL_FRAME_BITS * samplesPerBit;

    for (size_t i = 0; i < numSamples; ++i) {
        float hostL = inL[i];
        float hostR = inR[i];
        float hostMono = 0.5f * (std::abs(hostL) + std::abs(hostR));

        // Determine current bit and chip within frame
        size_t frameSampleIdx = mEmbedSampleCounter % totalFrameSamples;
        size_t bitIdx = frameSampleIdx / samplesPerBit;
        size_t sampleInBit = frameSampleIdx % samplesPerBit;
        size_t chipIdx = sampleInBit / SAMPLES_PER_CHIP;

        uint8_t bitVal = frameBits[bitIdx];
        float bitPolar = (bitVal == 1) ? 1.0f : -1.0f;
        float chipPolar = mPnSequence[chipIdx % CHIPS_PER_BIT];

        // Modulate with carrier sine
        float carrier = std::sin(mEmbedCarrierPhase);
        mEmbedCarrierPhase += carrierPhaseInc;
        if (mEmbedCarrierPhase >= 2.0f * kPi) {
            mEmbedCarrierPhase -= 2.0f * kPi;
        }

        // Psychoacoustic perceptual masking: scale watermark to audio envelope
        float maskingEnvelope = hostMono * 0.8f + 0.02f;
        float watermark = bitPolar * chipPolar * carrier * linearStrength * maskingEnvelope;

        outL[i] = hostL + watermark;
        outR[i] = hostR + watermark;

        mEmbedSampleCounter++;
    }
}

bool JZBroadcastAudioWatermarkSteganographyEngine::detectWatermark(const float* inL, const float* inR,
                                                                 size_t numSamples,
                                                                 uint32_t& outPayload,
                                                                 float& confidence) {
    if (!inL || !inR || numSamples == 0) return false;

    float carrierPhaseInc = 2.0f * kPi * mCarrierHz / mSampleRate;
    size_t samplesPerBit = CHIPS_PER_BIT * SAMPLES_PER_CHIP;

    static float currentBitAcc = 0.0f;
    static size_t currentBitSampleCount = 0;

    for (size_t i = 0; i < numSamples; ++i) {
        float monoSample = 0.5f * (inL[i] + inR[i]);

        // Demodulate with carrier sine
        float carrier = std::sin(mDetectCarrierPhase);
        mDetectCarrierPhase += carrierPhaseInc;
        if (mDetectCarrierPhase >= 2.0f * kPi) {
            mDetectCarrierPhase -= 2.0f * kPi;
        }

        float baseband = monoSample * carrier;

        // Correlate against PN chip
        size_t chipIdx = (currentBitSampleCount / SAMPLES_PER_CHIP) % CHIPS_PER_BIT;
        float chipPolar = mPnSequence[chipIdx];
        currentBitAcc += baseband * chipPolar;
        currentBitSampleCount++;

        // When a full bit period has elapsed
        if (currentBitSampleCount >= samplesPerBit) {
            uint8_t detectedBit = (currentBitAcc >= 0.0f) ? 1 : 0;
            mReceivedBits.push_back(detectedBit);

            currentBitAcc = 0.0f;
            currentBitSampleCount = 0;
        }
    }

    // Search for sync preamble across received bits
    if (mReceivedBits.size() >= TOTAL_FRAME_BITS) {
        for (size_t start = 0; start <= mReceivedBits.size() - TOTAL_FRAME_BITS; ++start) {
            // Check 16-bit preamble
            uint16_t testPreamble = 0;
            for (int b = 0; b < 16; ++b) {
                testPreamble = (testPreamble << 1) | mReceivedBits[start + b];
            }

            if (testPreamble == SYNC_PREAMBLE) {
                // Read 32-bit payload
                uint32_t decodedPay = 0;
                for (int b = 0; b < 32; ++b) {
                    decodedPay = (decodedPay << 1) | mReceivedBits[start + 16 + b];
                }

                // Read 16-bit CRC
                uint16_t decodedCrc = 0;
                for (int b = 0; b < 16; ++b) {
                    decodedCrc = (decodedCrc << 1) | mReceivedBits[start + 48 + b];
                }

                uint8_t pBytes[4];
                pBytes[0] = (decodedPay >> 24) & 0xFF;
                pBytes[1] = (decodedPay >> 16) & 0xFF;
                pBytes[2] = (decodedPay >> 8)  & 0xFF;
                pBytes[3] = (decodedPay)       & 0xFF;
                uint16_t calcCrc = calculateCrc16(pBytes, 4);

                if (calcCrc == decodedCrc) {
                    outPayload = decodedPay;
                    mLastDecodedPayload = decodedPay;
                    mLastValid = true;
                    confidence = 0.98f;
                    mLastConfidence = confidence;
                    mBitErrorRate = 0.0f;
                    return true;
                }
            }
        }
    }

    // Default if not synchronized yet
    outPayload = mLastDecodedPayload;
    confidence = mLastConfidence;
    return mLastValid;
}

