//*****************************************************************************
// The JAZZ++ Midi Sequencer
//
// BinauralAcousticRoomConvolverEngine.h - Virtual Acoustic Room Convolver
//
// Binaural early reflections & boundary decay convolver for spatial Atmos
// headphone monitoring (Abbey Road Studio 3 / Sunset Sound style shoebox room).
// Simulates 3D acoustic room geometry, image-source reflection taps with
// ITD/ILD head shadowing, and Sabine/Eyring diffuse reverberant decay.
//*****************************************************************************

#ifndef JAZZ_BINAURAL_ACOUSTIC_ROOM_CONVOLVER_ENGINE_H
#define JAZZ_BINAURAL_ACOUSTIC_ROOM_CONVOLVER_ENGINE_H

#include <vector>
#include <cmath>
#include <cstddef>
#include <algorithm>

namespace Jazz {

class JZBinauralAcousticRoomConvolverEngine {
public:
    struct ReflectionTap {
        float delaySamplesL = 0.0f;
        float delaySamplesR = 0.0f;
        float gainL = 0.0f;
        float gainR = 0.0f;
        float hfDamping = 0.8f;
        float filterStateL = 0.0f;
        float filterStateR = 0.0f;
    };

    struct Parameters {
        float roomLengthMeters = 8.5f;     // Shoebox room length (X/Y)
        float roomWidthMeters = 6.2f;      // Shoebox room width
        float roomHeightMeters = 3.4f;     // Shoebox room height
        float roomSizeFactor = 1.0f;       // Scale factor (0.5 to 2.0)
        float damping = 0.45f;             // Wall acoustic absorption / damping (0.05 to 0.95)
        float earlyReflectionLevelDb = -6.0f; // Early reflections level (-60 to 0 dB)
        float lateReverbLevelDb = -18.0f;  // Diffuse late decay level (-60 to 0 dB)
        float stereoSpread = 1.0f;         // Binaural stereo width (0.0 to 1.5)
        float dryWet = 0.35f;              // Wet mix ratio (0.0 = 100% dry, 1.0 = 100% wet)
        bool headphonesCrossfeed = true;   // Direct sound crossfeed & HRTF head shadow
        bool bypassed = false;
    };

    JZBinauralAcousticRoomConvolverEngine(float sampleRate = 48000.0f);
    ~JZBinauralAcousticRoomConvolverEngine() = default;

    void initialize(float sampleRate);
    void reset();

    void setParameters(const Parameters& params);
    const Parameters& getParameters() const { return m_params; }

    void setRoomDimensions(float lengthM, float widthM, float heightM);
    void setRoomSizeFactor(float factor);
    float getRoomSizeFactor() const { return m_params.roomSizeFactor; }

    void setDamping(float damping);
    float getDamping() const { return m_params.damping; }

    void setEarlyReflectionLevelDb(float db);
    float getEarlyReflectionLevelDb() const { return m_params.earlyReflectionLevelDb; }

    void setLateReverbLevelDb(float db);
    float getLateReverbLevelDb() const { return m_params.lateReverbLevelDb; }

    void setStereoSpread(float spread);
    float getStereoSpread() const { return m_params.stereoSpread; }

    void setDryWet(float wet);
    float getDryWet() const { return m_params.dryWet; }

    void setHeadphonesCrossfeed(bool enabled);
    bool isHeadphonesCrossfeedEnabled() const { return m_params.headphonesCrossfeed; }

    void setBypass(bool bypass);
    bool isBypassed() const { return m_params.bypassed; }

    // Acoustic Geometry & Telemetry
    float getRoomVolumeCubicMeters() const;
    float getTotalSurfaceAreaSquareMeters() const;
    int getEarlyReflectionCount() const;
    float getAverageAbsorption() const;
    float getRt60Seconds() const;

    // Audio Processing
    void processStereo(const float* inL, const float* inR, float* outL, float* outR, int numSamples);

private:
    void rebuildAcousticModel();
    void updateCombFilterGains();

    float m_sampleRate;
    Parameters m_params;

    // Early Reflection Taps for Left and Right source channels
    std::vector<ReflectionTap> m_tapsL; // Reflections generated by Left speaker
    std::vector<ReflectionTap> m_tapsR; // Reflections generated by Right speaker

    // Delay buffer for early reflections
    std::vector<float> m_delayBufferL;
    std::vector<float> m_delayBufferR;
    int m_bufferSize;
    int m_writePos;

    // Diffuse Late Reverb (4-channel Feedback Delay Network / Comb + Allpass)
    static constexpr int NUM_COMBS = 4;
    static constexpr int NUM_ALLPASS = 2;

    std::vector<float> m_combBuffers[NUM_COMBS];
    int m_combIndices[NUM_COMBS];
    int m_combSizes[NUM_COMBS];
    float m_combFeedback[NUM_COMBS];
    float m_combFilterState[NUM_COMBS];

    std::vector<float> m_allpassBuffers[NUM_ALLPASS];
    int m_allpassIndices[NUM_ALLPASS];
    int m_allpassSizes[NUM_ALLPASS];

    // Direct sound crossfeed filters
    float m_crossfeedL2R;
    float m_crossfeedR2L;
};

} // namespace Jazz

namespace jazz {
    using JZBinauralAcousticRoomConvolverEngine = Jazz::JZBinauralAcousticRoomConvolverEngine;
}

#endif // JAZZ_BINAURAL_ACOUSTIC_ROOM_CONVOLVER_ENGINE_H
